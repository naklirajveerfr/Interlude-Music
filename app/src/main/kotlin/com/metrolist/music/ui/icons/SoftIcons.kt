/**
 * Drop-in replacement for androidx's painterResource: with "Soft icons" on, icons that have a
 * Material Symbols Rounded counterpart are swapped in, everything else (logos, widgets) is untouched.
 */
@Composable
fun painterResource(@DrawableRes id: Int): Painter {
    val resolved = if (LocalSoftIcons.current) SoftIconMap[id] ?: id else id
    return androidx.compose.ui.res.painterResource(resolved)
}
